/** Bakes the drivable vehicle race routes (src/game/race-routing.ts) for world scales 4 and 6 into
 * src/game/race-routes.generated.ts. Run: bun scripts/bake-race-routes.ts   (takes a minute: it samples the real terrain)
 * Each scale runs in its own process because WORLD_SCALE is read once at module load. */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

if (process.env["BAKE_ONE"]) {
  const { rawVehicleCourses } = await import("../src/game/racing");
  const { routeCourse, drivablePoint, legDrivable } = await import("../src/game/race-routing");
  const { AREAS } = await import("../src/game/activities");
  type Baked = { p: [number, number][]; s?: { at: number; via: [number, number]; skipTo: number } };
  const out: Record<string, Baked> = {};
  const len = (pts: { x: number; z: number }[]) => pts.slice(1).reduce((L, p, i) => L + Math.hypot(p.x - pts[i]!.x, p.z - pts[i]!.z), 0);
  for (const c of rawVehicleCourses()) {
    const t0 = performance.now();
    let r = routeCourse(c.points);
    // a course that lost too much of itself (laid over a mountain's cliffs) moves to where the area can be driven:
    // the same shape shifted round its area and turned, keeping whichever placement routes most of its length
    const want = len(c.points);
    // closest to the authored length wins: a short route lost the course, a very long one is all detours
    const score = (t: { points: { x: number; z: number }[] } | null) => { if (!t) return -Infinity; const L = len(t.points) / want; return L <= 1.3 ? Math.min(L, 1) : 1.3 - (L - 1.3) * 1.5 - 0.3; };
    if (!r || score(r) < 0.8) {
      const a = AREAS[c.area]!, cx = c.points.reduce((s, p) => s + p.x, 0) / c.points.length, cz = c.points.reduce((s, p) => s + p.z, 0) / c.points.length;
      for (const rad of [0.25, 0.5, 0.75]) for (let k = 0; k < 8; k++) for (const turn of [0, Math.PI / 2]) {
        const ang = (k / 8) * Math.PI * 2, ox = a.x + Math.sin(ang) * a.radius * rad, oz = a.z + Math.cos(ang) * a.radius * rad, c0 = Math.cos(turn), s0 = Math.sin(turn);
        const moved = c.points.map((p) => { const dx = p.x - cx, dz = p.z - cz; return { x: ox + dx * c0 + dz * s0, z: oz - dx * s0 + dz * c0 }; });
        const t = routeCourse(moved);
        if (score(t) > score(r)) r = t;
        if (score(r) >= 0.92) break;
      }
    }
    if (r) console.error(`  ${c.id}: ${Math.round((len(r.points) / want) * 100)}% of its length`);
    console.error(`${c.id}: ${r ? `${r.points.length} gates, ${r.dropped} dropped` : "NO ROUTE"} (${Math.round(performance.now() - t0)} ms)`);
    if (!r) continue;
    const baked: Baked = { p: r.points.map((p) => [p.x, p.z]) };
    // the shortcut: a straight, drivable cut from the checkpoint before it to the one after, no longer than the route between
    // (only when the course kept its authored checkpoints, so the anchors line up, and was not moved)
    if (c.shortcut && r.dropped === 0 && r.anchors.length === c.points.length && Math.hypot(r.points[0]!.x - c.points[0]!.x, r.points[0]!.z - c.points[0]!.z) < 120) {
      const from = r.points[r.anchors[c.shortcut.at - 1]!]!, to = r.points[r.anchors[c.shortcut.skipTo]!]!;
      let routeLen = 0; for (let k = r.anchors[c.shortcut.at - 1]! + 1; k <= r.anchors[c.shortcut.skipTo]!; k++) routeLen += Math.hypot(r.points[k]!.x - r.points[k - 1]!.x, r.points[k]!.z - r.points[k - 1]!.z);
      let best: { x: number; z: number } | null = null;
      for (let rad = 0; rad <= 64 && !best; rad += 8) for (let k = 0; k < (rad ? 8 : 1) && !best; k++) {
        const v = { x: c.shortcut.via.x + Math.sin(k) * rad, z: c.shortcut.via.z + Math.cos(k) * rad };
        if (!drivablePoint(v.x, v.z) || !legDrivable(from, v) || !legDrivable(v, to)) continue;
        if (Math.hypot(v.x - from.x, v.z - from.z) + Math.hypot(to.x - v.x, to.z - v.z) <= routeLen * 0.98) best = v;
      }
      if (best) baked.s = { at: r.anchors[c.shortcut.at - 1]! + 1, via: [best.x, best.z], skipTo: r.anchors[c.shortcut.skipTo]! };
      console.error(`  ${c.id}: shortcut ${best ? "routed" : "dropped (no drivable cut)"}`);
    }
    out[c.id] = baked;
  }
  process.stdout.write(JSON.stringify(out));
} else {
  const all: Record<number, unknown> = {};
  for (const scale of [4, 6]) {
    const res = spawnSync("bun", [import.meta.path], { env: { ...process.env, BAKE_ONE: "1", WORLD_SCALE: String(scale) }, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] });
    if (res.status !== 0) throw new Error(`scale ${scale} failed`);
    all[scale] = JSON.parse(res.stdout);
  }
  const body = Object.entries(all).map(([s, routes]) => `  ${s}: {\n${Object.entries(routes as Record<string, unknown>).map(([id, b]) => `    "${id}": ${JSON.stringify(b)},`).join("\n")}\n  },`).join("\n");
  writeFileSync(new URL("../src/game/race-routes.generated.ts", import.meta.url), `/** Generated by scripts/bake-race-routes.ts — do not edit. Vehicle race courses routed over drivable ground, world coordinates per world scale. */\n/** p: the gates (world x, z); s: the routed shortcut, if any (gate indices into p) */\nexport type BakedRoute = { p: readonly (readonly [number, number])[]; s?: { at: number; via: readonly [number, number]; skipTo: number } };\nexport const BAKED_ROUTES: Record<number, Record<string, BakedRoute>> = {\n${body}\n};\n`);
  console.error("wrote src/game/race-routes.generated.ts");
}
